  # panel is what makes bar length directly comparable theme to theme.
  x_range <- range(gene_level$logFC, na.rm = TRUE)
  x_pad <- diff(x_range) * 0.05
  x_limits <- c(x_range[1] - x_pad, x_range[2] + x_pad)


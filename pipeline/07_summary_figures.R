te_ora_file <- file.path(dir_enrichment, "te_ora_results.tsv")
if (file.exists(go_pathway_file)) {
  ora_de <- read.delim(go_pathway_file)
  if (file.exists(te_ora_file)) {
    ora_te <- read.delim(te_ora_file)
    common_cols <- intersect(names(ora_de), names(ora_te))
    validated_ora <- bind_rows(ora_de[common_cols], ora_te[common_cols])
  } else {
    validated_ora <- ora_de
  }

  # Curated term -> theme mapping, built from what's actually present in
  # validated_ora above (see pipeline development notes) - not every GO
  # term found is biologically informative on its own (e.g. "transferase
  # activity", "intracellular organelle" are too generic to plot).
  theme_map <- c(
    "alkane catabolic process" = "Redox, lipid & cell-envelope metabolism",
    "oxidoreductase activity" = "Redox, lipid & cell-envelope metabolism",
    "fatty acid synthase activity" = "Redox, lipid & cell-envelope metabolism",
    "lipid metabolic process" = "Redox, lipid & cell-envelope metabolism",
    "mycolic acid biosynthetic process" = "Redox, lipid & cell-envelope metabolism",
    "glycolipid biosynthetic process" = "Redox, lipid & cell-envelope metabolism",
    "cyclopropane-fatty-acyl-phospholipid synthase activity" = "Redox, lipid & cell-envelope metabolism",
    "reactive oxygen species degradation" = "Redox, lipid & cell-envelope metabolism",
    "superoxide radicals degradation" = "Redox, lipid & cell-envelope metabolism",
    "DNA recombination" = "DNA damage / repair response",
    "DNA strand exchange activity" = "DNA damage / repair response",
    "host cell surface" = "Host interaction & secretion",
    "host cell endoplasmic reticulum" = "Host interaction & secretion",
    "cell envelope Sec protein transport complex" = "Host interaction & secretion",
    "symbiont-mediated suppression of host innate immune response" = "Host interaction & secretion"
  )

  bio_terms <- validated_ora %>%
    filter(Description %in% names(theme_map)) %>%
    mutate(
      theme = theme_map[Description],
      # Explicit factor with BOTH levels, even though some themes (e.g.
      # DNA damage/repair) only ever contain "Up" terms - otherwise
      # that panel's legend silently drops "Down", and patchwork's
      # guides="collect" then can't merge it with the other panels'
      # legends into one, producing two different-looking legends.
      direction = factor(case_when(
        grepl("down", GeneSet, ignore.case = TRUE) ~ "Down",
        grepl("up", GeneSet, ignore.case = TRUE)   ~ "Up",
        TRUE ~ "Up"
      ), levels = c("Up", "Down"))
    ) %>%
    # A handful of terms show up in more than one gene set (e.g. "DNA
    # strand exchange activity" in both RNA-seq and Ribo-seq up). Keep
    # only the strongest (lowest p.adjust) instance per term so each
    # gets exactly one bar - otherwise two rows for the same y position
    # silently stack into one misleading bar.
    arrange(p.adjust) %>%
    distinct(Description, .keep_all = TRUE) %>%
    # A couple of GO term names are long enough (>40 chars) to blow out
    # the shared left-axis margin for every panel, pushing the title/
    # subtitle off the right edge - wrapping onto 2 lines keeps every
    # panel's margin compact regardless of its longest label.
    mutate(label_wrapped = vapply(Description, function(s) paste(strwrap(s, width = 32), collapse = "\n"), character(1)))

  if (nrow(bio_terms) > 0) {
    # One mini bar-chart per theme, stacked via patchwork with each
    # panel's height set proportional to its row count (plus a fixed
    # amount for its own axis/title) - facet_wrap/facet_grid would
    # otherwise give the 2-term and 9-term themes the same panel
    # height, cramming the busier one until its wrapped labels collide.
    # Relying on patchwork to auto-collect legends across panels that
    # don't all draw both colors is fragile (a panel with only "Up" bars
    # renders a subtly different legend key, so collection silently
    # fails and shows two legends instead of one) - so instead, show the
    # legend on exactly one panel. That panel must itself contain BOTH
    # directions: with drop = FALSE, ggplot2 (3.5.x, confirmed
    # empirically - not fixable via guide_legend(override.aes=...))
    # renders a factor level with zero rows IN THAT PANEL as a blank,
    # colorless legend key rather than a normal one. Which theme has
    # both directions can change run to run, so it's picked dynamically
    # below rather than assumed to always be the last panel.
    make_theme_panel <- function(theme_name, show_x_axis, show_legend) {
      df <- bio_terms %>% filter(theme == theme_name)
      p <- ggplot(df, aes(x = -log10(p.adjust), y = reorder(label_wrapped, -p.adjust), fill = direction)) +
        geom_col(width = 0.65) +
        scale_fill_manual(values = c(Up = "#993C1D", Down = "#185FA5"), drop = FALSE) +
        labs(subtitle = theme_name, x = NULL, y = NULL, fill = "Direction") +
        theme_pub(21) +
        theme(plot.subtitle = element_text(face = "bold", color = "black", size = rel(1.1)),
              legend.position = if (show_legend) "bottom" else "none")
      if (!show_x_axis) {
        p <- p + theme(axis.text.x = element_blank(), axis.ticks.x = element_blank())
      } else {
        p <- p + labs(x = expression(-log[10](adjusted~p)))
      }
      p
    }

    themes_in_order <- c("DNA damage / repair response", "Host interaction & secretion",
                          "Redox, lipid & cell-envelope metabolism")
    theme_counts <- table(bio_terms$theme)[themes_in_order]

    both_directions <- vapply(themes_in_order, function(t) {
      length(unique(bio_terms$direction[bio_terms$theme == t])) >= 2
    }, logical(1))
    legend_theme <- if (any(both_directions)) themes_in_order[which(both_directions)[1]] else themes_in_order[length(themes_in_order)]

    panels <- lapply(seq_along(themes_in_order), function(i) {
      make_theme_panel(themes_in_order[i],
                        show_x_axis = (i == length(themes_in_order)),
                        show_legend = (themes_in_order[i] == legend_theme))
    })

    ora_source_note <- if (file.exists(te_ora_file)) {
      "Curated from GO/pathway ORA on DE- and TE-significant gene sets"
    } else {
      "Curated from GO/pathway ORA on DE-significant gene sets"
    }
    p_bio <- wrap_plots(panels, ncol = 1, heights = as.numeric(theme_counts) + 1.8) +
      plot_annotation(
        title = "Biological themes beyond translation shutdown",
        subtitle = ora_source_note,
        tag_levels = "A",
        theme = theme(plot.title = element_text(face = "bold", size = 25),
                      plot.subtitle = element_text(color = "grey40", size = 17),
                      plot.tag = element_text(face = "bold", size = 21))
      )

    save_pub(p_bio, "summary_biological_themes", width = 10, height = 13)
  } else {
    message("[12_summary_figures] No curated biological-theme terms found - skipping that figure.")
  }
} else {
  message("[12_summary_figures] Missing ORA result file(s) - skipping biological-themes figure.")
}


# Produces a small set of publication-ready figures summarizing the
# headline results. Not exhaustive - the per-gene-set/per-category
# dotplots from steps 06/07/09 already cover the enrichment detail - but
# Figure 7 below sums those dotplots up into one overview grid, so
# there's at least one place to see where enrichment signal exists
# across the whole search space without opening two dozen PNGs.
# Pure visualization: reads already-computed result tables, writes no
# new statistics, changes nothing else in the pipeline.
#
# Every figure is written as both a 300 dpi PNG (quick viewing) and a
# vector PDF (manuscript-ready) via the shared theme_pub()/save_pub()
# helpers below, and multi-panel figures carry bold A/B/C... tags.
# Full caption text for each one (the kind that goes under "Figure N."
# in the manuscript, not baked into the image) lives in
# results/figure_captions.txt, regenerated by this same step.
#
# Outputs (results/):
#   summary_volcano.{png,pdf}                     RNA-seq / Ribo-seq volcano plots
#   summary_transcriptome_vs_translatome.{png,pdf} logFC_rna vs logFC_ribo scatter
#   summary_de_categories.{png,pdf}                Co-regulated / Only RNA / Only Ribo bar chart
#   summary_top_enrichment.{png,pdf}               top enriched GO/pathway terms
#   summary_biological_themes.{png,pdf}            curated non-ribosomal GO/pathway themes
#   summary_holistic_gene_view.{png,pdf}           hand-picked gene-level logFC by theme
#   summary_enrichment_overview.{png,pdf}          enriched-term counts per gene set x annotation
#   figure_captions.txt                            manuscript-style caption text per figure

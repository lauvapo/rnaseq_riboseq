# ------------------------------------------------------------------
# Figure 1: volcano plots (RNA-seq and Ribo-seq side by side)
# ------------------------------------------------------------------
make_volcano <- function(logfc_col, padj_col, title) {
  df <- all_info %>%
    filter(!is.na(.data[[logfc_col]]), !is.na(.data[[padj_col]])) %>%
    mutate(
      neglog10padj = -log10(pmax(.data[[padj_col]], 1e-300)),
      direction = case_when(
        .data[[padj_col]] < fdr_cutoff & .data[[logfc_col]] >  logfc_cutoff ~ "Up",
        .data[[padj_col]] < fdr_cutoff & .data[[logfc_col]] < -logfc_cutoff ~ "Down",
        TRUE ~ "Not significant"
      )
    )
  labels <- df %>% filter(gene_symbol %in% highlight_symbols)

  ggplot(df, aes(x = .data[[logfc_col]], y = neglog10padj, color = direction)) +
    geom_point(alpha = 0.6, size = 2.4) +
    geom_vline(xintercept = c(-logfc_cutoff, logfc_cutoff), linetype = "dashed", color = "grey60", linewidth = 0.3) +
    geom_hline(yintercept = -log10(fdr_cutoff), linetype = "dashed", color = "grey60", linewidth = 0.3) +
    geom_text_repel(data = labels, aes(label = gene_symbol), color = "black", size = 6.5,
                     max.overlaps = 20, fontface = "italic", show.legend = FALSE) +
    geom_point(data = labels, color = "black", size = 3.2, shape = 21, fill = NA) +
    scale_color_manual(values = c(Up = "#FF6961FF", Down = "#4285F4FF", "Not significant" = "#D3D1C7")) +
    labs(title = title, x = "log2 fold-change", y = expression(-log[10](padj)), color = NULL) +
    theme_pub(21) +
    theme(legend.position = "bottom")
}

p_volcano <- (make_volcano("logFC_rna", "padj_rna", "RNA-seq") +

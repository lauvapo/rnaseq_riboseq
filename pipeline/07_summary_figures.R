de_geneset_levels <- c("RNA-seq up-regulated", "RNA-seq down-regulated",
                        "Ribo-seq up-regulated", "Ribo-seq down-regulated")

# Counts every (GeneSet, Annotation) cell, including combinations with
# zero enriched terms (tidyr::complete(), using the factor levels set
# above) - a blank/near-white tile is as informative here as a dark one,
# since it shows where ORA found nothing rather than silently omitting
# that cell from the grid.
count_enrichment <- function(file, geneset_levels, source_label) {
  if (!file.exists(file)) return(NULL)
  ora <- read.delim(file)
  ora %>%
    mutate(GeneSet = factor(GeneSet, levels = geneset_levels),
           Annotation = factor(Annotation, levels = annotation_levels)) %>%
    group_by(GeneSet, Annotation) %>%
    summarise(n_terms = n(), .groups = "drop") %>%
    tidyr::complete(GeneSet, Annotation, fill = list(n_terms = 0)) %>%
    mutate(source = source_label)
}

enrichment_counts <- count_enrichment(go_pathway_file, de_geneset_levels, "DE-based ORA")

if (!is.null(enrichment_counts) && nrow(enrichment_counts) > 0) {
  # rev() so "RNA-seq up-regulated" reads at the top.
  enrichment_counts$geneset_label <- factor(
    as.character(enrichment_counts$GeneSet),
    levels = rev(de_geneset_levels)
  )
  max_n <- max(enrichment_counts$n_terms, na.rm = TRUE)

  p_enrich_overview <- ggplot(enrichment_counts, aes(x = Annotation, y = geneset_label, fill = n_terms)) +
    geom_tile(color = "white", linewidth = 0.7) +
    geom_text(aes(label = n_terms, color = n_terms > max_n / 2), size = 6, show.legend = FALSE) +
    scale_fill_gradient(low = "grey96", high = "#0F6E56", name = "Enriched\nterms") +
    scale_color_manual(values = c("TRUE" = "white", "FALSE" = "grey25"), guide = "none") +
    labs(title = "Enrichment landscape overview",
         subtitle = "Enriched terms per gene set and annotation category",
         x = NULL, y = NULL) +
    theme_pub(21) +
    theme(panel.grid = element_blank(), axis.text.x = element_text(angle = 20, hjust = 1))

  save_pub(p_enrich_overview, "summary_enrichment_overview", width = 10, height = 6)
} else {
  message("[12_summary_figures] No ORA result files found - skipping enrichment overview figure.")
}


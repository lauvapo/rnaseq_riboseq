    } else {
      p <- p + labs(x = "log2 fold-change")
    }
    p
  }

  gene_counts <- table(factor(curated_genes$theme, levels = theme_order))
  panels <- lapply(seq_along(theme_order), function(i) {
    make_gene_panel(theme_order[i], show_x_axis = (i == length(theme_order)), show_legend = (i == length(theme_order)))

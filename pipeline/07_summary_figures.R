# --- Shared publication styling ---
# One theme + one save routine used by every figure below, so the whole
# set reads as one coherent figure system rather than N independently
# tweaked plots. Journal-style choices: no panel border, faint major
# gridlines only (no minor), thin grey axis lines instead of a boxed
# panel, compact legend keys. base_size defaults to 15pt - deliberately
# large, since these figures are meant to be legible when placed at
# print size in a paper (a normal-looking size on a full screen becomes
# illegibly small once shrunk into a single manuscript column), not
# optimized for how big they look at 100% on a screen.
theme_pub <- function(base_size = 21) {
  theme_minimal(base_size = base_size, base_family = "sans") +
    theme(
      panel.grid.minor  = element_blank(),
      panel.grid.major  = element_line(color = "grey88", linewidth = 0.3),
      axis.line         = element_line(color = "grey20", linewidth = 0.35),
      axis.ticks        = element_line(color = "grey20", linewidth = 0.35),
      axis.ticks.length = unit(1.3, "pt"),
      legend.key.size   = unit(0.32, "cm"),
      legend.text       = element_text(size = rel(0.85)),
      legend.title      = element_text(size = rel(0.9)),
      plot.title        = element_text(face = "bold", size = rel(1.05)),
      plot.subtitle     = element_text(color = "grey35", size = rel(0.85)),
      strip.text        = element_text(face = "bold", size = rel(0.95)),
      plot.margin       = margin(5.5, 8, 5.5, 5.5)
    )
}

# Saves every figure as both a 300 dpi PNG (quick viewing) and a vector
# PDF (what a journal submission actually wants) from the same ggplot/
# patchwork object, at a print-appropriate size in inches - so every
# figure in results/ is ready to drop into a manuscript without a
# separate export pass.
save_pub <- function(plot, basename, width, height) {
  ggsave(file.path(dir_results, paste0(basename, ".png")), plot,
         width = width, height = height, dpi = 300, bg = "white", limitsize = FALSE)
  ggsave(file.path(dir_results, paste0(basename, ".pdf")), plot,
         width = width, height = height, device = cairo_pdf, bg = "white", limitsize = FALSE)
  ggsave(file.path(dir_results, paste0(basename, ".svg")), plot,
         width = width, height = height, bg = "white", limitsize = FALSE)
}

